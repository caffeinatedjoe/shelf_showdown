/**
 * Regenerates modules/coverFiles.js from the JPEGs in covers/.
 *
 *   node scripts/generate-cover-files.mjs
 */
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const coversDir = path.join(root, "covers");
const outFile = path.join(root, "modules", "coverFiles.js");

const files = (await readdir(coversDir))
  .filter((name) => /\.jpe?g$/i.test(name))
  .sort((a, b) => a.localeCompare(b, "en"));

const body = `/**
 * Filenames under covers/, generated by scripts/generate-cover-files.mjs.
 * Do not edit by hand — re-run the script after adding JPEGs.
 */
export const COVER_FILES = ${JSON.stringify(files, null, 2)};
`;

await writeFile(outFile, body);
console.log(`Wrote ${files.length} cover filenames to ${path.relative(root, outFile)}`);
